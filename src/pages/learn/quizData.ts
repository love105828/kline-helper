/* ================== 随机工具 ================== */
function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** 打乱单题的选项顺序并同步调整正确答案索引 */
function shuffleOptions(q: Q): Q {
  const idx = shuffle(q.opts.map((_, i) => i));
  return {
    ...q,
    opts: idx.map((i) => q.opts[i]),
    ans: idx.indexOf(q.ans),
  };
}

/** 取一套测试：合并内置+补充题库，题目与选项均随机排序 */
export function getQuizSet(key: string): { name: string; qs: Q[] } {
  const base = BANK[key] || BANK.zs;
  const extra = (EXTRA_BANK as any)[key] || [];
  const merged = shuffle([...base.qs, ...extra]).map(shuffleOptions);
  return { name: base.name, qs: merged };
}

